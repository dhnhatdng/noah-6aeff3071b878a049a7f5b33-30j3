    fullName: string;
    role: string;
    organization: string;
    location: string;
    description: string;
    expertise: string[];
    skills: string[];
    projects: [string, string][];
    experienceLevel: ExperienceLevel;
    experience: string;
    interests: string[];
    website?: string;
    whoIAm: IdentityOption[];
    building: string;
    canOffer: ExchangeOption[];
