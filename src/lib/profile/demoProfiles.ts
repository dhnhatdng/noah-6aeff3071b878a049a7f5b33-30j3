/** Free-text search across name, role, organisation, location, skills and topics. */
export const demoMatchesQuery = (p: DemoProfile, query: string): boolean => {
    const q = query.trim().toLowerCase();
    if (!q) return true;
    return [
        p.fullName,
        p.role,
        p.organization,
        p.location,
        ...p.expertise,
        ...p.skills,
        ...p.interests,
        ...p.matchmaking.meetingTopics,
    ]
        .join(' ')
        .toLowerCase()
        .includes(q);
};
